"""
Main execution script for Ethiopia Digital Finance Analysis
Runs complete analysis pipeline and generates all outputs
"""

import sys
from pathlib import Path
import warnings
warnings.filterwarnings('ignore')

# Add src to path
sys.path.append(str(Path(__file__).parent / 'src'))

from data_analysis import EthiopiaDataAnalyzer
from visualization_engine import VisualizationEngine
from impact_modeling import ImpactModeler

def main():
    """Run complete analysis pipeline"""
    
    print("🚀 ETHIOPIA DIGITAL FINANCE ANALYSIS PIPELINE")
    print("=" * 60)
    print("Starting comprehensive analysis...")
    
    try:
        # Step 1: Data Analysis & Enrichment
        print("\n📊 STEP 1: DATA ANALYSIS & ENRICHMENT")
        print("-" * 45)
        
        analyzer = EthiopiaDataAnalyzer()
        analysis_results = analyzer.run_full_analysis()
        
        if analysis_results is None:
            print("❌ Data analysis failed. Stopping pipeline.")
            return
        
        print("✅ Data analysis complete!")
        
        # Step 2: Visualization Generation
        print("\n🎨 STEP 2: VISUALIZATION GENERATION")
        print("-" * 40)
        
        viz_engine = VisualizationEngine()
        viz_results = viz_engine.generate_all_visualizations()
        
        print("✅ Visualizations complete!")
        
        # Step 3: Impact Modeling & Forecasting
        print("\n🤖 STEP 3: IMPACT MODELING & FORECASTING")
        print("-" * 45)
        
        modeler = ImpactModeler()
        modeling_results = modeler.run_complete_modeling()
        
        print("✅ Impact modeling complete!")
        
        # Step 4: Summary Report
        print("\n📋 STEP 4: GENERATING SUMMARY REPORT")
        print("-" * 40)
        
        generate_summary_report(analysis_results, viz_results, modeling_results)
        
        print("✅ Summary report generated!")
        
        # Final Summary
        print("\n🎉 ANALYSIS PIPELINE COMPLETE!")
        print("=" * 50)
        print("📊 Data Analysis: ✅ Complete")
        print("🎨 Visualizations: ✅ Complete") 
        print("🤖 Impact Modeling: ✅ Complete")
        print("📋 Reports: ✅ Complete")
        print("🌐 Dashboard: Ready to run")
        
        print("\n📁 OUTPUT FILES GENERATED:")
        print("   📊 figures/ - All visualization files")
        print("   📋 tables/ - Summary and forecast tables")
        print("   💾 data/processed/ - Cleaned datasets")
        print("   🌐 dashboard/app.py - Interactive dashboard")
        
        print("\n🚀 TO RUN DASHBOARD:")
        print("   streamlit run dashboard/app.py")
        
        return True
        
    except Exception as e:
        print(f"❌ Pipeline failed with error: {e}")
        return False

